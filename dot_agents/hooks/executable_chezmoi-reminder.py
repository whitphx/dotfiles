#!/usr/bin/env -S python3 -I
"""PostToolUse hook for Claude Code and Codex: flag edits to chezmoi-managed files.

Both agents read `hookSpecificOutput.additionalContext` from a PostToolUse hook,
so one script serves both. They differ only in how the edited paths arrive.
"""

import json
import os
import re
import subprocess
import sys

PATCH_PATH = re.compile(r"^\*\*\* (?:Add File|Update File|Delete File|Move to): (.+)$", re.M)
# chezmoi renders these sources into their targets, so `chezmoi add` would
# clobber them with the rendered output instead of updating them.
GENERATED_SOURCE = re.compile(r"/modify_[^/]*$|\.tmpl$")


def edited_paths(event):
    tool_input = event.get("tool_input") or {}
    for key in ("file_path", "notebook_path"):
        if tool_input.get(key):
            yield tool_input[key]
    # Codex reports every file edit as apply_patch, with the patch text in `command`.
    command = tool_input.get("command")
    if event.get("tool_name") == "apply_patch" and isinstance(command, str):
        yield from PATCH_PATH.findall(command)


def chezmoi(*args):
    # A GUI-launched agent may not inherit the PATH entry chezmoi lives on,
    # and a hook that crashes there would error on every single edit.
    try:
        result = subprocess.run(["chezmoi", *args], capture_output=True, text=True)
    except OSError:
        return None
    return os.path.realpath(result.stdout.strip()) if result.returncode == 0 else None


def main():
    try:
        event = json.load(sys.stdin)
    except ValueError:
        return
    cwd = os.path.realpath(event.get("cwd") or os.getcwd())
    # Edited paths are resolved below, so these must be too for the prefix checks to match.
    home = os.path.realpath(os.path.expanduser("~"))
    source_dir = None
    notes = []

    for path in dict.fromkeys(edited_paths(event)):
        # Resolve symlinks so ~/.codex/AGENTS.md maps to the managed ~/.agents/AGENTS.md.
        path = os.path.realpath(os.path.join(cwd, os.path.expanduser(path)))
        if not path.startswith(home + os.sep):
            continue
        source_dir = source_dir or chezmoi("source-path")
        if source_dir and path.startswith(source_dir + os.sep):
            # A session working in the source repo already knows; the note is for edits made from elsewhere.
            if not (cwd + os.sep).startswith(source_dir + os.sep):
                notes.append(f"{path} is in the chezmoi source repo. Commit it there, and run `chezmoi apply` if it has a target.")
            continue
        source = chezmoi("source-path", path)
        if not source:
            continue
        if GENERATED_SOURCE.search(source):
            notes.append(
                f"{path} is generated by chezmoi from {source}. `chezmoi add` would overwrite that source, "
                f"so make this change in the source instead, run `chezmoi apply {path}`, then commit in the source repo."
            )
        else:
            notes.append(f"{path} is chezmoi-managed, not git-managed. Run `chezmoi add {path}`, then commit in the source repo.")

    if notes:
        json.dump({"hookSpecificOutput": {"hookEventName": "PostToolUse", "additionalContext": "\n".join(notes)}}, sys.stdout)


if __name__ == "__main__":
    main()
